_HEADER = (
    "<!-- Generated by src.paper_3 · run {run_id} · commit {commit} · {ts}\n"
    "     Source of record: data/paper_3_audit/{name}. Do not edit by hand —\n"
    "     re-run `python -m src.paper_3.cli --step publish` instead. -->\n"
)


def git_commit() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short", "HEAD"],
                             cwd=str(PROJECT_ROOT), capture_output=True,
                             text=True, timeout=10)
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def run(out_dir: Path | None = None, publish_dir: Path | None = None,
        run_id: str = "") -> list[Path]:
    """Copy every available deliverable. Missing ones are reported, not fatal."""
    source = Path(out_dir) if out_dir else OUT_DIR
    target = Path(publish_dir) if publish_dir else PUBLISH_DIR
    target.mkdir(parents=True, exist_ok=True)

    commit = git_commit()
    ts = datetime.now(timezone.utc).isoformat(timespec="seconds")
    published: list[Path] = []
    missing: list[str] = []

    for rel in PUBLISHED:
        src = source / rel
        if not src.exists():
            missing.append(rel)
            continue
        dst = target / Path(rel).name
        if src.suffix == ".md":
            header = _HEADER.format(run_id=run_id or "unset", commit=commit,
                                    ts=ts, name=rel)
            dst.write_text(header + src.read_text(encoding="utf-8"), encoding="utf-8")
        else:
            shutil.copy2(src, dst)
        published.append(dst)
        logger.info("published %s", dst.name)

    if missing:
        logger.warning("not published (not produced yet): %s", ", ".join(missing))
    return published

"""Copy the finished deliverables from data/ into the tracked paper_3_audit/.

A symlink would not work: `data/` is git-ignored, so a symlinked `paper_3_audit/`
would commit a pointer into an untracked tree and the deliverables would be
unreachable from a fresh clone. Plain copies are what get committed.

`*.parquet` is git-ignored globally, so only `.md` and `.csv` are published; the
parquet intermediates stay in `data/paper_3_audit/` as the working record.
"""
